#!/usr/bin/env python3
"""
Platform Sync Generator for .deepx/

Generates platform-specific configuration files from the canonical .deepx/
knowledge base. Supports output to:
  - .github/copilot-instructions.md  (GitHub Copilot)
  - .claude/                          (Claude Code / CLAUDE.md)
  - .cursor/rules/                    (Cursor)
  - .vscode/                          (VS Code settings)

Usage:
    python3 generate_platforms.py [--deepx-root DIR] [--output-root DIR]
                                  [--platforms PLATFORM ...]
                                  [--dry-run] [--force]

Exit codes:
    0  All files generated successfully
    1  Generation error
    2  .deepx/ directory not found
"""

import argparse
import json
import os
import re
import sys
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional, Set


# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

SUPPORTED_PLATFORMS = ["github", "claude", "cursor", "vscode"]

DEEPX_ROOT_DEFAULT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
)

GENERATED_HEADER = (
    "<!-- AUTO-GENERATED by .deepx/scripts/generate_platforms.py -->\n"
    "<!-- Do not edit directly. Source of truth: .deepx/ -->\n"
    "<!-- Generated: {timestamp} -->\n\n"
)


# ---------------------------------------------------------------------------
# Knowledge base reader
# ---------------------------------------------------------------------------

class DeepXReader:
    """Read and parse .deepx/ knowledge base files."""

    def __init__(self, deepx_root: str):
        self.root = deepx_root

    def read_file(self, rel_path: str) -> Optional[str]:
        """Read a file relative to .deepx/ root."""
        full = os.path.join(self.root, rel_path)
        if os.path.isfile(full):
            return Path(full).read_text(encoding="utf-8", errors="replace")
        return None

    def list_category(self, category: str) -> List[str]:
        """List files in a category directory."""
        cat_dir = os.path.join(self.root, category)
        if not os.path.isdir(cat_dir):
            return []
        return sorted(f for f in os.listdir(cat_dir)
                       if not f.startswith("."))

    def extract_skills(self) -> List[Dict[str, str]]:
        """Extract skill metadata from skill files."""
        skills = []
        for filename in self.list_category("skills"):
            if not filename.endswith(".md"):
                continue
            content = self.read_file(f"skills/{filename}")
            if not content:
                continue

            # Extract title from first heading
            title_match = re.search(r'^#\s+(.+)$', content, re.MULTILINE)
            title = title_match.group(1) if title_match else filename

            # Extract description from first paragraph after heading
            desc_match = re.search(
                r'^#\s+.+\n+(?:>.*\n+)*(.+?)(?:\n\n|\n#)',
                content, re.MULTILINE
            )
            desc = desc_match.group(1).strip() if desc_match else ""

            # Derive command name
            command = "/" + filename.replace(".md", "")

            skills.append({
                "command": command,
                "title": title,
                "description": desc,
                "filename": filename,
            })
        return skills

    def extract_elements_summary(self) -> List[Dict[str, str]]:
        """Extract element summary from dx-stream-elements.md."""
        content = self.read_file("toolsets/dx-stream-elements.md")
        if not content:
            return []

        elements = []
        # Match ## N. ElementName patterns
        pattern = re.compile(
            r'^##\s+\d+\.\s+(\w+)\s*\n+\*\*Description:\*\*\s*(.+?)(?:\n\n|\n\*\*)',
            re.MULTILINE | re.DOTALL
        )
        for match in pattern.finditer(content):
            elements.append({
                "name": match.group(1),
                "description": match.group(2).strip().split("\n")[0],
            })
        return elements

    def extract_routing_table(self) -> List[Dict[str, str]]:
        """Extract context routing table entries."""
        # Build from known structure
        return [
            {
                "trigger": "Pipeline, detection, classification",
                "files": ".deepx/skills/dx-build-pipeline-app.md, "
                         ".deepx/toolsets/dx-stream-elements.md",
            },
            {
                "trigger": "MQTT, Kafka, message broker",
                "files": ".deepx/skills/dx-build-mqtt-kafka-app.md, "
                         ".deepx/toolsets/dx-stream-elements.md",
            },
            {
                "trigger": "Multi-model, cascaded, tiled",
                "files": ".deepx/skills/dx-build-pipeline-app.md, "
                         ".deepx/toolsets/dx-stream-metadata.md",
            },
            {
                "trigger": "Model, download",
                "files": ".deepx/skills/dx-model-management.md",
            },
            {
                "trigger": "Validation, testing",
                "files": ".deepx/skills/dx-validate.md, "
                         ".deepx/instructions/testing-patterns.md",
            },
            {
                "trigger": "ALWAYS read (every task)",
                "files": ".deepx/memory/common_pitfalls.md, "
                         ".deepx/instructions/coding-standards.md",
            },
        ]

    def extract_conventions(self) -> List[str]:
        """Extract critical conventions from coding-standards.md."""
        content = self.read_file("instructions/coding-standards.md")
        if not content:
            return []

        conventions = []
        # Extract numbered section titles
        pattern = re.compile(r'^###\s+\d+\.\s+(.+)$', re.MULTILINE)
        for match in pattern.finditer(content):
            conventions.append(match.group(1).strip())
        return conventions

    def extract_pitfalls(self) -> List[Dict[str, str]]:
        """Extract pitfall summaries from common_pitfalls.md."""
        content = self.read_file("memory/common_pitfalls.md")
        if not content:
            return []

        pitfalls = []
        pattern = re.compile(
            r'^##\s+\d+\.\s+\[(\w+)\]\s+(.+?)$\n+'
            r'\*\*Symptom:\*\*\s*(.+?)$',
            re.MULTILINE
        )
        for match in pattern.finditer(content):
            pitfalls.append({
                "tag": match.group(1),
                "title": match.group(2).strip(),
                "symptom": match.group(3).strip(),
            })
        return pitfalls



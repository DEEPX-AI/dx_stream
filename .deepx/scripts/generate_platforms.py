def generate_github_copilot(reader: DeepXReader) -> str:
    """Generate .github/copilot-instructions.md."""
    # Read template if available
    template = reader.read_file("templates/copilot-instructions.md")
    if template:
        # Perform template substitutions
        output = template

        # {ROUTING_TABLE}
        routing = reader.extract_routing_table()
        table_rows = []
        for entry in routing:
            table_rows.append(
                f"| **{entry['trigger']}** | {entry['files']} |"
            )
        routing_table = (
            "| If the task mentions... | Read these files |\n"
            "|---|---|\n" +
            "\n".join(table_rows)
        )
        output = output.replace("{ROUTING_TABLE}", routing_table)

        # {SKILLS_TABLE}
        skills = reader.extract_skills()
        skill_rows = []
        for s in skills:
            skill_rows.append(f"| `{s['command']}` | {s['description']} |")
        skills_table = (
            "| Command | Description |\n"
            "|---------|-------------|\n" +
            "\n".join(skill_rows)
        )
        output = output.replace("{SKILLS_TABLE}", skills_table)

        # {ELEMENTS_TABLE}
        elements = reader.extract_elements_summary()
        elem_rows = []
        for e in elements:
            elem_rows.append(f"| `{e['name']}` | {e['description']} |")
        elements_table = (
            "| Element | Purpose |\n"
            "|---------|--------|\n" +
            "\n".join(elem_rows)
        )
        output = output.replace("{ELEMENTS_TABLE}", elements_table)

        # {CONVENTIONS_LIST}
        conventions = reader.extract_conventions()
        conv_list = "\n".join(f"{i+1}. **{c}**" for i, c in enumerate(conventions))
        output = output.replace("{CONVENTIONS_LIST}", conv_list)

        # {PITFALLS_LIST}
        pitfalls = reader.extract_pitfalls()
        pit_list = "\n".join(
            f"- **[{p['tag']}] {p['title']}**: {p['symptom']}"
            for p in pitfalls
        )
        output = output.replace("{PITFALLS_LIST}", pit_list)

        return output

    # Fallback: generate from scratch
    return _generate_copilot_from_scratch(reader)


def _generate_copilot_from_scratch(reader: DeepXReader) -> str:
    """Generate copilot instructions without template."""
    lines = [
        "# dx_stream — GitHub Copilot Instructions\n",
        "> GStreamer-based video analytics framework for DEEPX NPU.\n",
        "## Context Routing Table\n",
    ]

    routing = reader.extract_routing_table()
    lines.append("| If the task mentions... | Read these files |")
    lines.append("|---|---|")
    for entry in routing:
        lines.append(f"| **{entry['trigger']}** | {entry['files']} |")

    lines.append("\n## Skills\n")
    skills = reader.extract_skills()
    lines.append("| Command | Description |")
    lines.append("|---------|-------------|")
    for s in skills:
        lines.append(f"| `{s['command']}` | {s['description']} |")

    lines.append("\n## 13 GStreamer Elements\n")
    elements = reader.extract_elements_summary()
    lines.append("| Element | Purpose |")
    lines.append("|---------|---------|")
    for e in elements:
        lines.append(f"| `{e['name']}` | {e['description']} |")

    lines.append("\n## Critical Conventions\n")
    conventions = reader.extract_conventions()
    for i, c in enumerate(conventions):
        lines.append(f"{i+1}. **{c}**")

    lines.append("\n## Common Pitfalls\n")
    pitfalls = reader.extract_pitfalls()
    for p in pitfalls:
        lines.append(f"- **[{p['tag']}] {p['title']}**: {p['symptom']}")

    return "\n".join(lines) + "\n"



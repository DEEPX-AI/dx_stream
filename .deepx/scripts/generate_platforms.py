GENERATORS = {
    "github": lambda r: {".github/copilot-instructions.md":
                          generate_github_copilot(r)},
    "claude": generate_claude,
    "cursor": generate_cursor,
    "vscode": generate_vscode,
}


def generate(deepx_root: str, output_root: str,
             platforms: List[str], dry_run: bool = False,
             force: bool = False) -> int:
    """Generate platform files from .deepx/ knowledge base."""
    reader = DeepXReader(deepx_root)
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    errors = 0

    for platform in platforms:
        if platform not in GENERATORS:
            print(f"[ERROR] Unknown platform: {platform}")
            errors += 1
            continue

        print(f"\n--- Generating: {platform} ---")
        generator = GENERATORS[platform]
        try:
            files = generator(reader)
        except Exception as e:
            print(f"[ERROR] Generator failed for {platform}: {e}")
            errors += 1
            continue

        for rel_path, content in files.items():
            full_path = os.path.join(output_root, rel_path)

            # Check for existing file
            if os.path.isfile(full_path) and not force:
                # Check if it was auto-generated
                try:
                    existing = Path(full_path).read_text(
                        encoding="utf-8", errors="replace"
                    )
                    if "AUTO-GENERATED by .deepx/" not in existing:
                        print(f"  [SKIP] {rel_path} (manually edited, "
                              f"use --force to overwrite)")
                        continue
                except Exception:
                    pass

            # Add generated header for markdown files
            if rel_path.endswith(".md"):
                content = GENERATED_HEADER.format(timestamp=timestamp) + content

            if dry_run:
                print(f"  [DRY-RUN] Would write: {rel_path} "
                      f"({len(content)} bytes)")
            else:
                # Create directory if needed
                os.makedirs(os.path.dirname(full_path), exist_ok=True)
                Path(full_path).write_text(content, encoding="utf-8")
                print(f"  [WROTE] {rel_path} ({len(content)} bytes)")

    return errors


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def parse_args():
    parser = argparse.ArgumentParser(
        description="Generate platform configs from .deepx/ knowledge base"
    )
    parser.add_argument(
        "--deepx-root",
        default=DEEPX_ROOT_DEFAULT,
        help="Path to .deepx/ directory (default: auto-detect)"
    )
    parser.add_argument(
        "--output-root",
        default=None,
        help="Output root directory (default: parent of .deepx/)"
    )
    parser.add_argument(
        "--platforms", nargs="+",
        default=SUPPORTED_PLATFORMS,
        choices=SUPPORTED_PLATFORMS,
        help="Platforms to generate for (default: all)"
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Show what would be generated without writing files"
    )
    parser.add_argument(
        "--force", action="store_true",
        help="Overwrite manually-edited files"
    )
    parser.add_argument(
        "--list-platforms", action="store_true",
        help="List supported platforms and exit"
    )
    return parser.parse_args()


def main():
    args = parse_args()

    if args.list_platforms:
        print("Supported platforms:")
        for p in SUPPORTED_PLATFORMS:
            print(f"  - {p}")
        sys.exit(0)

    deepx_root = args.deepx_root
    if not os.path.isdir(deepx_root):
        print(f"[ERROR] .deepx/ directory not found: {deepx_root}")
        sys.exit(2)

    # Default output root is the parent of .deepx/
    output_root = args.output_root
    if output_root is None:
        output_root = os.path.dirname(deepx_root)

    print(f"Source:  {deepx_root}")
    print(f"Output:  {output_root}")
    print(f"Platforms: {', '.join(args.platforms)}")

    errors = generate(
        deepx_root=deepx_root,
        output_root=output_root,
        platforms=args.platforms,
        dry_run=args.dry_run,
        force=args.force,
    )

    if errors:
        print(f"\n[DONE] Completed with {errors} error(s)")
        sys.exit(1)
    else:
        print("\n[DONE] All platforms generated successfully")
        sys.exit(0)


if __name__ == "__main__":
    main()
